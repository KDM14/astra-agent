"""Memory entry models and categorization."""

from __future__ import annotations

import datetime
import uuid
from enum import Enum
from typing import Any, Dict, Optional
from pydantic import BaseModel, Field


class MemoryCategory(str, Enum):
    """Explicit epistemological status of memory."""
    USER_FACT = "USER_FACT"               # Ground truth provided by user
    TOOL_RESULT = "TOOL_RESULT"           # Verified output from executed tool
    ENVIRONMENT_EVIDENCE = "ENVIRONMENT_EVIDENCE" # Inspected filesystem or system state
    MODEL_HYPOTHESIS = "MODEL_HYPOTHESIS" # Unverified inference generated by LLM


class MemoryEntry(BaseModel):
    """An individual unit of memory with strict provenance."""
    entry_id: str = Field(default_factory=lambda: f"mem_{uuid.uuid4().hex[:8]}")
    task_id: str
    category: MemoryCategory
    key: str
    content: str
    metadata: Dict[str, Any] = Field(default_factory=dict)
    confidence: float = Field(default=1.0, ge=0.0, le=1.0)
    created_at: datetime.datetime = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))
    updated_at: datetime.datetime = Field(default_factory=lambda: datetime.datetime.now(datetime.timezone.utc))
